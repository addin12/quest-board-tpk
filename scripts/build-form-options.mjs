// The words the Google Forms and the site must agree on, from one source (src/lib/i18n/en.ts, categories.ts, systems.ts):
//   - docs/form-options.md      the options to paste into the forms' multiple-choice, checkbox and dropdown questions
//   - apps-script/Code.gs       the GENRE_LABELS / STYLE_LABELS between the GENERATED markers (option text -> key)
// `npm run form-options` rewrites both; a unit test fails while either is stale.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { en } from "../src/lib/i18n/en.ts";
import { GENRES, STYLES } from "../src/lib/categories.ts";
import { SYSTEMS } from "../src/lib/systems.ts";

const ROOT = path.join(import.meta.dirname, "..");
const BEGIN = "// BEGIN GENERATED LABELS (npm run form-options: the form's option text -> the site's key)";
const END = "// END GENERATED LABELS";

const labelMap = (items, prefix) => Object.fromEntries(items.map((i) => [en[`${prefix}.${i.key}`], i.key]));

/** The generated block for Code.gs. */
export function labelsBlock() {
  const lit = (o) => `{\n${Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n}`;
  return [
    BEGIN,
    `const GENRE_LABELS = ${lit(labelMap(GENRES, "genre"))};`,
    `const STYLE_LABELS = ${lit(labelMap(STYLES, "style"))};`,
    END,
  ].join("\n");
}

/** docs/form-options.md */
export function optionsMarkdown() {
  const list = (items) => items.map((s) => `- ${s}`).join("\n");
  return `# Form options

GENERATED by \`npm run form-options\` from the site's own words: don't edit by hand. Paste each list into the form
question named in the heading (Google Forms: the question's three-dot menu → "Bulk edit options" is not available,
so paste one option per line with the question's "Add option" field; for dropdowns, Forms accepts a pasted list).
The option text must be exactly as written here: the script turns it back into the site's categories.

## Game form

### Game system (dropdown)
${list(SYSTEMS)}

### Format (multiple choice)
${list([en["format.one_shot"], en["format.campaign"]])}

### Genres (pick up to 3) (checkboxes)
${list(GENRES.map((g) => en[`genre.${g.key}`]))}

### Play styles (pick up to 3) (checkboxes)
${list(STYLES.map((s) => en[`style.${s.key}`]))}

### Where will you play? (multiple choice)
${list([en["loc.online"], en["loc.inPerson"]])}

### Time zone (dropdown)
- WIB
- WITA
- WIT

### Play language (multiple choice)
${list([en["lang.gameId"], en["lang.gameEn"], en["lang.gameBoth"]])}

### Experience level (multiple choice)
${list([en["level.beginner"], en["level.any"], en["level.experienced"]])}
`;
}

/** Code.gs with its generated block replaced. */
export function patchedScript(source) {
  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start < 0 || end < 0) throw new Error("Code.gs has no GENERATED LABELS markers");
  return source.slice(0, start) + labelsBlock() + source.slice(end + END.length);
}

if (process.argv[1]?.endsWith("build-form-options.mjs")) {
  const gs = path.join(ROOT, "apps-script", "Code.gs");
  writeFileSync(gs, patchedScript(readFileSync(gs, "utf8")));
  writeFileSync(path.join(ROOT, "docs", "form-options.md"), optionsMarkdown());
  console.log("[form-options] apps-script/Code.gs and docs/form-options.md are up to date");
}
