// One command that creates everything the backend needs in the owner's Cloudflare account, after one `wrangler login`:
//
//   npx wrangler login            (opens a Cloudflare consent page: the only step that needs a person)
//   npm run cloudflare:setup      (add -- --dry to only print what it would do)
//
// It makes the D1 database and the R2 bucket, applies the migrations, writes wrangler.toml (so the Pages project gets the bindings
// from the repo), generates the secrets, and stores them as Pages secrets. Safe to run again: what exists is reused, and a secret
// that is already stored is kept. Nothing secret is written to the repo; the build key and the mail secret go to .cloudflare.local.json
// (git-ignored) so the owner can paste them where they are asked for.
//
// NOT TESTED against a real account (this was written without access to one): run with --dry first and read what it prints.
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.join(import.meta.dirname, "..");
const DRY = process.argv.includes("--dry");
const PROJECT = process.env.CF_PAGES_PROJECT || "quest-board-tpk";
const DB_NAME = "quest-board";
const BUCKET = "quest-board-images";
const WRANGLER = "npx --yes wrangler@4";
const LOCAL = path.join(ROOT, ".cloudflare.local.json");

function run(command, input) {
  console.log(`$ ${command}`);
  if (DRY) return "";
  return execSync(command, { cwd: ROOT, encoding: "utf8", input, stdio: ["pipe", "pipe", "inherit"] });
}

const local = existsSync(LOCAL) ? JSON.parse(readFileSync(LOCAL, "utf8")) : {};
const secret = () => randomBytes(32).toString("base64url");
local.buildKey ||= secret();
local.turnstileSecret ||= "";

// 1. D1
let databaseId = local.databaseId || "";
if (!databaseId) {
  const out = run(`${WRANGLER} d1 create ${DB_NAME} --json`) || "{}";
  try {
    databaseId = JSON.parse(out).uuid || JSON.parse(out).database_id || "";
  } catch {
    const list = run(`${WRANGLER} d1 list --json`) || "[]";
    databaseId = JSON.parse(list).find((d) => d.name === DB_NAME)?.uuid ?? "";
  }
}
if (!databaseId && !DRY) throw new Error(`Could not find or create the D1 database "${DB_NAME}". Is wrangler logged in?`);
local.databaseId = databaseId;

// 2. R2
try {
  run(`${WRANGLER} r2 bucket create ${BUCKET}`);
} catch {
  console.log(`(the bucket ${BUCKET} probably exists already)`);
}

// 3. wrangler.toml: the Pages project reads its bindings from here
const toml = `# Generated by scripts/cloudflare-setup.mjs. The bindings of the Pages project; the secrets are not here (they are Pages secrets).
name = "${PROJECT}"
pages_build_output_dir = "out"
compatibility_date = "2026-10-01"
compatibility_flags = ["nodejs_compat"]

[[d1_databases]]
binding = "DB"
database_name = "${DB_NAME}"
database_id = "${databaseId}"
migrations_dir = "worker/migrations"

[[r2_buckets]]
binding = "IMAGES"
bucket_name = "${BUCKET}"

[vars]
SITE_URL = "https://${PROJECT}.pages.dev"
OWNER_EMAIL = "${process.env.OWNER_EMAIL || "CHANGE-ME@example.com"}"
`;
if (!DRY) writeFileSync(path.join(ROOT, "wrangler.toml"), toml);
else console.log(`(would write wrangler.toml with database_id ${databaseId || "<new>"})`);

// 4. Migrations
run(`${WRANGLER} d1 migrations apply ${DB_NAME} --remote`);

// 5. Secrets (Pages secrets are write-only: never read back, so only put what is new)
const mailSecret = (() => {
  const f = path.join(ROOT, ".apps-script.local.json");
  return existsSync(f) ? JSON.parse(readFileSync(f, "utf8")).mailSecret || "" : "";
})();
const put = (name, value) => {
  if (!value) return console.log(`(skipping ${name}: no value yet)`);
  run(`${WRANGLER} pages secret put ${name} --project-name ${PROJECT}`, `${value}\n`);
};
put("BUILD_KEY", local.buildKey);
put("MAIL_SECRET", mailSecret);
put("TURNSTILE_SECRET", local.turnstileSecret);

if (!DRY) writeFileSync(LOCAL, `${JSON.stringify(local, null, 2)}\n`);
console.log(`
Done${DRY ? " (dry run: nothing was changed)" : ""}. What is left, and what you must paste where (values are in .cloudflare.local.json, never in the repo):
  1. Pages → Settings → Variables: TPK_API_BASE = https://${PROJECT}.pages.dev and TPK_BUILD_KEY = the buildKey from .cloudflare.local.json.
  2. Pages → Settings → Variables: OWNER_EMAIL (also edit it in wrangler.toml), MAIL_RELAY_URL = your Apps Script web app address (…/exec), DEPLOY_HOOK = the build hook address.
  3. npm run script:deploy  (puts the mail relay into your Apps Script; it makes .apps-script.local.json's mailSecret) then run this script again to store it.
  4. Optional: a Turnstile widget (Cloudflare dashboard → Turnstile): its site key is NEXT_PUBLIC_TURNSTILE_SITE_KEY, its secret is TURNSTILE_SECRET.
  5. GitHub → repo → Settings → Secrets: BUILD_KEY (the same value). It lets the scheduled job (.github/workflows/cron.yml) rebuild and back up.`);
