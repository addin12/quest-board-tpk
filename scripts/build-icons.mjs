// Copies the outlines of the icons listed in src/lib/icons.ts out of Phosphor Icons (MIT) into src/components/icon-data.ts.
//
//   npm run icons
//
// The site ships only these few outlines as inline SVG: no icon font, no request, and no credit line is needed in the page (the MIT
// notice is kept in THIRD_PARTY_NOTICES.md).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ICON_FILES } from "../src/lib/icons.ts";

const pkgDir = path.join(import.meta.dirname, "..", "node_modules", "@phosphor-icons", "core");
const outFile = path.join(import.meta.dirname, "..", "src", "components", "icon-data.ts");

const entries = Object.entries(ICON_FILES).map(([name, file]) => {
  const svg = readFileSync(path.join(pkgDir, "assets", "regular", `${file}.svg`), "utf8");
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1]?.trim();
  if (!inner) throw new Error(`No outline found in ${file}.svg`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},`;
});

writeFileSync(outFile, `// Generated by scripts/build-icons.mjs from Phosphor Icons (https://phosphoricons.com, MIT licence, see THIRD_PARTY_NOTICES.md). Do not edit.
// Each value is the inner markup of a 256 x 256 outline; Icon draws it with the current text colour.
import type { IconName } from "@/lib/icons";

export const ICON_MARKUP: Record<IconName, string> = {
${entries.join("\n")}
};
`);
console.log(`${entries.length} icons written to ${path.relative(process.cwd(), outFile)}`);
